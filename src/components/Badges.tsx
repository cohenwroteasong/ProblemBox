import { Ban, ChevronDown, ChevronsUp, CircleCheck, CircleDot, Flame, Minus, Sparkles, Timer } from 'lucide-react';
import type { Priority, Status } from '../../shared/types';
import { PRIORITY_LABEL, STATUS_LABEL } from '../lib/format';

const STATUS_ICON = { new: CircleDot, in_progress: Timer, resolved: CircleCheck, dismissed: Ban } as const;
const STATUS_VAR = { new: 'new', in_progress: 'progress', resolved: 'resolved', dismissed: 'dismissed' } as const;

export function StatusBadge({ status, size = 'md' }: { status: Status; size?: 'sm' | 'md' }) {
  const Icon = STATUS_ICON[status];
  const v = STATUS_VAR[status];
  return (
    <span
      className={`inline-flex shrink-0 items-center gap-1 rounded-full font-semibold ${size === 'sm' ? 'h-5 px-1.5 text-[11px]' : 'h-6 px-2 text-xs'}`}
      style={{ color: `var(--st-${v})`, background: `var(--st-${v}-soft)` }}
    >
      <Icon size={size === 'sm' ? 11 : 13} strokeWidth={2.4} aria-hidden />
      {STATUS_LABEL[status]}
    </span>
  );
}

const PRIORITY_ICON = { urgent: Flame, high: ChevronsUp, normal: Minus, low: ChevronDown } as const;

export function PriorityBadge({ priority, size = 'md', quiet = false }: { priority: Priority; size?: 'sm' | 'md'; quiet?: boolean }) {
  const Icon = PRIORITY_ICON[priority];
  if (quiet && (priority === 'normal' || priority === 'low')) {
    return (
      <span className="inline-flex items-center gap-1 text-xs font-medium text-ink-3">
        <Icon size={13} strokeWidth={2.4} aria-hidden />
        {PRIORITY_LABEL[priority]}
      </span>
    );
  }
  return (
    <span
      className={`inline-flex shrink-0 items-center gap-1 rounded-full font-semibold ${size === 'sm' ? 'h-5 px-1.5 text-[11px]' : 'h-6 px-2 text-xs'}`}
      style={{ color: `var(--pr-${priority})`, background: `var(--pr-${priority}-soft)` }}
    >
      <Icon size={size === 'sm' ? 11 : 13} strokeWidth={2.4} aria-hidden />
      {PRIORITY_LABEL[priority]}
    </span>
  );
}

export function PriorityBar({ priority }: { priority: Priority }) {
  // A slim leading rule on list rows; the badge beside it carries the label.
  const show = priority === 'urgent' || priority === 'high';
  return <span aria-hidden className="w-[3px] shrink-0 self-stretch rounded-full" style={{ background: show ? `var(--pr-${priority})` : 'transparent' }} />;
}

export function BoxChip({ name, color, className = '' }: { name: string; color: string; className?: string }) {
  return (
    <span className={`inline-flex min-w-0 items-center gap-1.5 text-xs font-medium text-ink-2 ${className}`}>
      <span className="size-2 shrink-0 rounded-full" style={{ background: color }} aria-hidden />
      <span className="truncate">{name}</span>
    </span>
  );
}

export function SimulatedTag() {
  return (
    <span className="inline-flex items-center gap-1 rounded-md border border-dashed border-line-strong px-1.5 text-[10px] font-semibold tracking-wide text-ink-3 uppercase" title="Generated by the live demo feed">
      <Sparkles size={10} aria-hidden />
      Simulated
    </span>
  );
}
